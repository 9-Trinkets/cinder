export const DEFAULT_UI_LOCALE = 'en'

export const LOCALES: Record<string, Record<MessageKey, string>> = {
  en,
  'zh-TW': zhTW,
}

/** Human-readable names for locales the web UI itself can render. */
export const LOCALE_LABELS: Record<string, string> = {
  en: 'English',
  'zh-TW': '繁體中文',
}

/** Falls back to the default locale when the UI has no strings for `code`. */
export function resolveLocale(code: string | null | undefined): string {
  if (code && LOCALES[code]) return code
  return DEFAULT_UI_LOCALE
}
